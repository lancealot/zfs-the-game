/**
 * RAIDZ geometry and parity, following vdev_raidz_map_alloc():
 * a block's sectors are split into columns (one per disk), parity columns
 * first, data filled column by column, and the allocation rounded up to a
 * multiple of (parity + 1) sectors with "skip" sectors.
 */

export type CellKind = 'P' | 'Q' | 'R' | 'D' | 'skip'

export interface Cell {
  kind: CellKind
  /** Which disk (child vdev) the sector lands on. */
  disk: number
  /** Sector index on that disk, relative to the vdev's start. */
  row: number
  /** For data: index of the sector within the block. For parity: the row within the column. */
  index: number
  /** Column within the block's stripe (parity columns first), and position down that column. */
  col: number
  k: number
  value: number
}

export interface RaidzMap {
  width: number
  parity: number
  dataSectors: number
  /** Allocated sectors including parity and skip sectors. */
  asize: number
  cells: Cell[]
}

/** Lays out a block of `data` sectors (one byte stands in for each sector) starting at vdev sector `start`. */
export function raidzMap(data: number[], width: number, parity: number, start = 0): RaidzMap {
  const s = data.length
  const dcols = width
  const q = Math.floor(s / (dcols - parity))
  const r = s - q * (dcols - parity)
  const bc = r === 0 ? 0 : r + parity
  const tot = s + parity * (q + (r === 0 ? 0 : 1))
  const acols = q === 0 ? bc : dcols
  const sizes: number[] = []
  for (let c = 0; c < acols; c++) sizes.push(c < bc ? q + 1 : q)

  const cells: Cell[] = []
  const covered = new Set<number>()
  const place = (c: number, k: number) => {
    const sector = start + c + k * dcols
    covered.add(sector)
    return { disk: sector % dcols, row: Math.floor(sector / dcols), col: c, k }
  }
  // Data columns, filled one after another.
  let di = 0
  const dataCols: number[][] = []
  for (let c = parity; c < acols; c++) {
    const col: number[] = []
    for (let k = 0; k < sizes[c]; k++) {
      const v = data[di]
      cells.push({ kind: 'D', ...place(c, k), index: di, value: v })
      col.push(v)
      di++
    }
    dataCols.push(col)
  }
  // Parity columns.
  const rows = sizes[0] ?? 0
  const kinds: CellKind[] = ['P', 'Q', 'R']
  for (let p = 0; p < parity; p++) {
    for (let k = 0; k < rows; k++) {
      const row = dataCols.map((col) => col[k])
      const value = p === 0 ? xorAll(row) : p === 1 ? qParity(row) : rParity(row)
      cells.push({ kind: kinds[p], ...place(p, k), index: k, value })
    }
  }
  const asize = Math.ceil(tot / (parity + 1)) * (parity + 1)
  for (let sec = start; sec < start + asize; sec++) {
    if (covered.has(sec)) continue
    cells.push({ kind: 'skip', disk: sec % dcols, row: Math.floor(sec / dcols), index: -1, col: -1, k: -1, value: 0 })
  }
  return { width, parity, dataSectors: s, asize, cells }
}

const xorAll = (vals: Array<number | undefined>) => vals.reduce<number>((a, v) => a ^ (v ?? 0), 0)

// ---------------------------------------------------------------- GF(2^8)
// ZFS uses the field generated by x^8 + x^4 + x^3 + x^2 + 1 (0x11d).

const EXP = new Uint8Array(512)
const LOG = new Uint8Array(256)
{
  let x = 1
  for (let i = 0; i < 255; i++) {
    EXP[i] = x
    LOG[x] = i
    x <<= 1
    if (x & 0x100) x ^= 0x11d
  }
  for (let i = 255; i < 512; i++) EXP[i] = EXP[i - 255]
}

export function gfMul(a: number, b: number) {
  if (a === 0 || b === 0) return 0
  return EXP[LOG[a] + LOG[b]]
}

export function gfDiv(a: number, b: number) {
  if (b === 0) throw new Error('divide by zero')
  if (a === 0) return 0
  return EXP[(LOG[a] + 255 - LOG[b]) % 255]
}

export function gfPow2(n: number) {
  return EXP[((n % 255) + 255) % 255]
}

/** Q = sum of 2^(n-1-i) * D_i, evaluated Horner-style as ZFS does. */
export function qParity(row: Array<number | undefined>) {
  let q = 0
  for (const v of row) q = gfMul(q, 2) ^ (v ?? 0)
  return q
}

/** R uses generator 4. */
export function rParity(row: Array<number | undefined>) {
  let r = 0
  for (const v of row) r = gfMul(r, 4) ^ (v ?? 0)
  return r
}

/** Rebuilds one missing data value from P parity: XOR everything else. */
export function reconstructP(row: Array<number | null>, p: number) {
  return xorAll(row.map((v) => v ?? 0)) ^ p
}

/** Rebuilds two missing data values (indices x < y) from P and Q. */
export function reconstructPQ(row: Array<number | null>, x: number, y: number, p: number, q: number): [number, number] {
  const n = row.length
  const known = row.map((v, i) => (i === x || i === y ? 0 : (v ?? 0)))
  const pxy = p ^ xorAll(known)
  const qxy = q ^ qParity(known)
  const ax = gfPow2(n - 1 - x)
  const ay = gfPow2(n - 1 - y)
  // pxy = Dx ^ Dy ; qxy = ax*Dx ^ ay*Dy  =>  Dx = (qxy ^ ay*pxy) / (ax ^ ay)
  const dx = gfDiv(qxy ^ gfMul(ay, pxy), ax ^ ay)
  return [dx, pxy ^ dx]
}

/** Parity and padding overhead of a block, as a fraction of its allocation. */
export function overhead(m: RaidzMap) {
  return 1 - m.dataSectors / m.asize
}
